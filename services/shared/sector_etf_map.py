def all_etf_codes() -> set:
    """返回映射涉及的全部 ETF 代码（供收盘采集使用）"""
    codes = set()
    for cands in SECTOR_ETF_CANDIDATES.values():
        for c in cands:
            codes.add(c["code"])
    for v in SECTOR_ETF_MAP.values():
        codes.add(v["code"])
    return codes


def default_etf(sector_name: str):
    """按板块名取默认（首个）候选 ETF，未命中返回 None"""
    cands = SECTOR_ETF_CANDIDATES.get(sector_name)
    if cands:
        return cands[0]
    # 回退：按 SECTOR_MAP 反查代码再取 ETF
    for code, name in SECTOR_MAP.items():
        if name == sector_name:
            return SECTOR_ETF_MAP.get(code)
    return None
